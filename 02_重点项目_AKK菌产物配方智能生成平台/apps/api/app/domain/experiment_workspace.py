def _workspace(
    *,
    experiment_id: str,
    name: str,
    objective: str,
    batch_code: str | None,
    current_stage: str,
    status: str,
    status_label: str,
    result_summary: str,
    confidence_score: float | None,
    updated_at: str,
    model_version: str,
    result_version: str | None = None,
    model_type: str,
    stages: list[dict],
    result_metrics: list[dict],
    risk_items: list[str],
    validation_items: list[str],
    data_reliability: dict | None = None,
) -> dict:
    confidence_value = confidence_score or 0
    return {
        "experimentId": experiment_id,
        "name": name,
        "objective": objective,
        "batchCode": batch_code,
        "currentStage": current_stage,
        "status": status,
        "statusLabel": status_label,
        "resultSummary": result_summary,
        "confidenceScore": confidence_score,
        "updatedAt": updated_at,
        "modelVersion": model_version,
        "resultVersion": result_version,
        "modelType": model_type,
        "reliabilityMetrics": [
            data_reliability
            or {"label": "数据完整度", "value": "94.2%", "detail": "6/6 设备数据已对齐"},
            {
                "label": "综合模型可靠性",
                "value": f"{confidence_value * 100:.1f}%" if confidence_score is not None else "--",
                "detail": model_version,
            },
            {"label": "待人工确认", "value": str(len(validation_items)), "detail": "需要研发人员确认"},
        ],
        "stages": stages,
        "resultMetrics": result_metrics,
        "riskItems": risk_items,
        "validationItems": validation_items,
    }


