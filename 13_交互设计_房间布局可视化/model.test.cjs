const assert = require('node:assert/strict');
const fs = require('node:fs');
assert.ok(fs.existsSync('./model.js'), 'Room model implementation is missing');
const M = require('./model.js');
const s = M.initial();
assert.deepEqual(s.bath, {w:3.3,d:1.7});
assert.equal(s.room.w*s.room.d-s.bath.w*s.bath.d,24.39);
const box = {id:'test',name:'测试家具',x:4,y:4,w:2,d:1,h:1,z:0,angle:90,visible:true,zone:'room'};
const b = M.bounds(box);
assert.ok(Math.abs(b.maxX-b.minX-1)<1e-9);
assert.ok(Math.abs(b.maxY-b.minY-2)<1e-9);
assert.ok(M.warnings({...box,x:4.8},s).some(t=>t.includes('房间')));
assert.ok(M.warnings({...box,x:1,y:1,angle:0},s).some(t=>t.includes('卫生间')));
assert.equal(M.parse(JSON.stringify(s)).objects.length,s.objects.length);
assert.throws(()=>M.parse('{"objects":[]}'));
const bad=M.initial(); bad.objects[0].w=-1;
assert.throws(()=>M.parse(JSON.stringify(bad)));
const bad2=M.initial(); bad2.openings.windowW=8;
assert.throws(()=>M.parse(JSON.stringify(bad2)));
console.log('PASS: bathroom orientation, rotated bounds, collision and JSON validation');
