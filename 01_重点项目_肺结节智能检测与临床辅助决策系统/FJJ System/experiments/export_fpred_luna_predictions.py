import argparse
import csv
import json
from pathlib import Path


def read_csv(path):
    with Path(path).open("r", encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def read_manifest(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _as_float(row, key):
    return float(row[key])


def _check_identity(candidate, manifest, prediction, index):
    fields = ["seriesuid", "class"]
    for field in fields:
        values = {str(candidate.get(field, "")), str(manifest.get(field, "")), str(prediction.get(field, ""))}
        if len(values) != 1:
            raise ValueError(f"row {index} {field} mismatch: candidate={candidate.get(field)} manifest={manifest.get(field)} prediction={prediction.get(field)}")
    if manifest.get("patch") and prediction.get("patch") and str(manifest["patch"]) != str(prediction["patch"]):
        raise ValueError(f"row {index} patch mismatch: manifest={manifest.get('patch')} prediction={prediction.get('patch')}")


def align_predictions_to_candidates(candidates, manifest, predictions):
    ok_manifest = [row for row in manifest if row.get("status") == "ok"]
    if len(candidates) < len(ok_manifest):
        raise ValueError(f"candidate rows fewer than ok manifest rows: {len(candidates)} < {len(ok_manifest)}")
    if len(predictions) != len(ok_manifest):
        raise ValueError(f"prediction rows do not match ok manifest rows: {len(predictions)} != {len(ok_manifest)}")

    rows = []
    for index, (candidate, item, prediction) in enumerate(zip(candidates, ok_manifest, predictions)):
        _check_identity(candidate, item, prediction, index)
        rows.append({
            "seriesuid": candidate["seriesuid"],
            "coordX": _as_float(candidate, "coordX"),
            "coordY": _as_float(candidate, "coordY"),
            "coordZ": _as_float(candidate, "coordZ"),
            "probability": _as_float(prediction, "probability"),
        })
    return rows


def write_predictions(path, rows):
    with Path(path).open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["seriesuid", "coordX", "coordY", "coordZ", "probability"])
        writer.writeheader()
        writer.writerows(rows)


def write_seriesuids(path, rows):
    seriesuids = sorted({row["seriesuid"] for row in rows})
    Path(path).write_text("\n".join(seriesuids) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description="Export FPRED patch probabilities as LUNA-style detection predictions.")
    parser.add_argument("--candidates", required=True, help="Candidate CSV used to extract patches.")
    parser.add_argument("--manifest", required=True, help="Patch manifest generated by extract_luna16_patches.py.")
    parser.add_argument("--predictions", required=True, help="FPRED predictions generated from the manifest.")
    parser.add_argument("--out", required=True, help="Output LUNA-style CSV.")
    parser.add_argument("--seriesuids-out", help="Optional output text file with unique seriesuids.")
    args = parser.parse_args()

    candidates = read_csv(args.candidates)
    manifest = read_manifest(args.manifest)
    predictions = read_csv(args.predictions)
    rows = align_predictions_to_candidates(candidates, manifest, predictions)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    write_predictions(out, rows)
    if args.seriesuids_out:
        write_seriesuids(args.seriesuids_out, rows)
    print(json.dumps({"prediction_count": len(rows), "series_count": len({row["seriesuid"] for row in rows}), "out": str(out)}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
