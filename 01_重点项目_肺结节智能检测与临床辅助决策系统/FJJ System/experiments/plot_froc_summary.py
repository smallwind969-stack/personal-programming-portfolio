import argparse
import csv
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt


mpl.rcParams.update({
    "font.family": "sans-serif",
    "font.sans-serif": ["Microsoft YaHei", "SimHei", "Arial", "DejaVu Sans"],
    "pdf.fonttype": 42,
    "svg.fonttype": "none",
    "axes.spines.right": False,
    "axes.spines.top": False,
    "legend.frameon": False,
})


def read_summary(path):
    data = {}
    with Path(path).open("r", encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            data[row["metric"]] = float(row["value"])
    return data


def main():
    parser = argparse.ArgumentParser(description="Plot FROC/CPM summary generated by froc_eval.py.")
    parser.add_argument("--summary", required=True)
    parser.add_argument("--out", default="docs/world_frontier/local_proxy_froc/froc_summary_plot.png")
    parser.add_argument("--title", default="Local review-proxy FROC")
    parser.add_argument("--cpm-label", default="Proxy CPM")
    args = parser.parse_args()

    data = read_summary(args.summary)
    rates = [0.125, 0.25, 0.5, 1.0, 2.0, 4.0, 8.0]
    sensitivity = [data[f"sensitivity_at_{rate}_fp_per_scan"] for rate in rates]
    cpm = data["cpm"]

    fig, ax = plt.subplots(figsize=(6.4, 3.4))
    ax.plot(rates, sensitivity, marker="o", color="#3182bd", linewidth=2)
    ax.set_xscale("log", base=2)
    ax.set_xticks(rates)
    ax.set_xticklabels([str(rate) for rate in rates])
    ax.set_ylim(0, 1.05)
    ax.set_xlabel("False positives per scan")
    ax.set_ylabel("Sensitivity")
    ax.set_title(args.title)
    ax.text(
        0.98,
        0.10,
        f"{args.cpm_label} = {cpm:.4f}",
        ha="right",
        transform=ax.transAxes,
        fontsize=10,
        color="#333333",
    )
    ax.grid(axis="y", color="#eeeeee")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    for ext in ("png", "pdf", "svg"):
        fig.savefig(out.with_suffix(f".{ext}"), dpi=600 if ext == "png" else None, bbox_inches="tight")
    plt.close(fig)
    print(out.with_suffix(".png"))


if __name__ == "__main__":
    main()
